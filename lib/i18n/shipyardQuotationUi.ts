const TABLES: Record<ShipyardQuoteLocale, Record<ShipyardQuoteUiKey, string>> = {
  en: EN,
  zh: ZH,
  ja: JA,
  fil: FIL,
  tr: TR,
  ko: KO,
};

/** Bundled packs for offline seed and API responses. */
export function getShipyardQuoteBundledTables(): Record<
  ShipyardQuoteLocale,
  Record<ShipyardQuoteUiKey, string>
> {
  return TABLES;
}

export function shipyardQuoteUi(locale: ShipyardQuoteLocale, key: ShipyardQuoteUiKey): string {
  if (typeof window !== "undefined") {
    try {
      // Ignore stale packs so newly shipped translations (e.g. login fil/tr/ko) take effect.
      const bundledVersion = Number(EN.packVersion ?? "1");
      let cachedVersion = 0;
      try {
        const metaRaw = window.localStorage.getItem("actinium.shipyard.i18n.packs.meta.v1");
        if (metaRaw) {
          cachedVersion = Number((JSON.parse(metaRaw) as { version?: string }).version ?? "0");
        }
      } catch {
        /* ignore meta */
      }
      const raw = window.localStorage.getItem("actinium.shipyard.i18n.packs.v1");
      if (raw) {
        const packs = JSON.parse(raw) as Partial<
          Record<ShipyardQuoteLocale, Partial<Record<ShipyardQuoteUiKey, string>>>
        >;
        if (!cachedVersion) {
          cachedVersion = Number(packs.en?.packVersion ?? "0");
        }
        if (cachedVersion >= bundledVersion) {
          const fromLocale = packs[locale]?.[key];
          if (fromLocale) return fromLocale;
          const fromEn = packs.en?.[key];
          if (fromEn) return fromEn;
        }
      }
    } catch {
      /* fall through to bundle */
    }
  }
  return TABLES[locale]?.[key] ?? EN[key];
}

export function parseShipyardQuoteLocale(value: string | null | undefined): ShipyardQuoteLocale {
  if (value === "zh" || value === "ja" || value === "fil" || value === "tr" || value === "ko" || value === "en") {
    return value;
  }
  return "en";
}

export const SHIPYARD_QUOTE_LANG_STORAGE_KEY = "actinium.shipyardQuote.lang";
export const SHIPYARD_QUOTE_LANG_INIT_KEY = "actinium.shipyardQuote.lang.initialized";

export type ShipyardQuoteLangPrefs = {
  mode: ShipyardQuoteLanguageMode;
  secondary: Exclude<ShipyardQuoteLocale, "en">;
  /** Which language drives labels when dual; English always selectable. */
  active: ShipyardQuoteLocale;
  /** Set when prefs were chosen from location/browser detection. */
  autoDetected?: boolean;
};

export const DEFAULT_SHIPYARD_QUOTE_LANG_PREFS: ShipyardQuoteLangPrefs = {
  mode: "en_only",
  secondary: "zh",
  active: "en",
};

export function loadShipyardQuoteLangPrefs(): ShipyardQuoteLangPrefs {
  if (typeof window === "undefined") return DEFAULT_SHIPYARD_QUOTE_LANG_PREFS;
  try {
    const raw = window.localStorage.getItem(SHIPYARD_QUOTE_LANG_STORAGE_KEY);
    if (!raw) return DEFAULT_SHIPYARD_QUOTE_LANG_PREFS;
    const parsed = JSON.parse(raw) as Partial<ShipyardQuoteLangPrefs>;
    const mode = parsed.mode === "dual" ? "dual" : "en_only";
    const secondary = parseShipyardQuoteLocale(parsed.secondary);
    const secondarySafe =
      secondary === "en" ? DEFAULT_SHIPYARD_QUOTE_LANG_PREFS.secondary : secondary;
    let active = parseShipyardQuoteLocale(parsed.active);
    if (mode === "en_only") active = "en";
    else if (active !== "en" && active !== secondarySafe) active = secondarySafe;
    return {
      mode,
      secondary: secondarySafe,
      active,
      autoDetected: parsed.autoDetected === true,
    };
  } catch {
    return DEFAULT_SHIPYARD_QUOTE_LANG_PREFS;
  }
}

export function saveShipyardQuoteLangPrefs(prefs: ShipyardQuoteLangPrefs) {
  if (typeof window === "undefined") return;
  window.localStorage.setItem(SHIPYARD_QUOTE_LANG_STORAGE_KEY, JSON.stringify(prefs));
  window.dispatchEvent(new Event("actinium-shipyard-lang"));
}

/**
 * First visit: detect location/browser language and enable dual English + local.
 * Subsequent visits keep the saved preference (manual or auto).
 * Never blocks login forever — geo/detect failures fall back to English within a timeout.
 */
export async function ensureShipyardQuoteLangPrefs(): Promise<ShipyardQuoteLangPrefs> {
  if (typeof window === "undefined") return DEFAULT_SHIPYARD_QUOTE_LANG_PREFS;

  const raw = window.localStorage.getItem(SHIPYARD_QUOTE_LANG_STORAGE_KEY);
  if (raw) return loadShipyardQuoteLangPrefs();

  const initialized = window.localStorage.getItem(SHIPYARD_QUOTE_LANG_INIT_KEY) === "1";
  if (initialized) return DEFAULT_SHIPYARD_QUOTE_LANG_PREFS;

  const withTimeout = <T,>(promise: Promise<T>, ms: number): Promise<T | null> =>
    Promise.race([
      promise.then((value) => value as T | null).catch(() => null),
      new Promise<null>((resolve) => {
        window.setTimeout(() => resolve(null), ms);
      }),
    ]);

  try {
    const detectMod = await withTimeout(import("@/lib/i18n/detectShipyardLocale"), 2500);
    if (!detectMod) {
      window.localStorage.setItem(SHIPYARD_QUOTE_LANG_INIT_KEY, "1");
      return DEFAULT_SHIPYARD_QUOTE_LANG_PREFS;
    }

    const { detectLocaleFromClientHints, pickDetectedLocale, localeFromCountryCode } = detectMod;

    let fromGeo: ReturnType<typeof localeFromCountryCode> = null;
    try {
      const controller = new AbortController();
      const timer = window.setTimeout(() => controller.abort(), 1500);
      const res = await fetch("/api/geo/locale", { cache: "no-store", signal: controller.signal });
      window.clearTimeout(timer);
      if (res.ok) {
        const data = (await res.json()) as { locale?: string | null; country?: string | null };
        fromGeo =
          (data.locale as ReturnType<typeof localeFromCountryCode>) ??
          localeFromCountryCode(data.country);
      }
    } catch {
      /* offline / local dev / aborted — fall through to browser + timezone */
    }

    const detected = pickDetectedLocale(fromGeo, detectLocaleFromClientHints());
    window.localStorage.setItem(SHIPYARD_QUOTE_LANG_INIT_KEY, "1");

    if (!detected) {
      return DEFAULT_SHIPYARD_QUOTE_LANG_PREFS;
    }

    const prefs: ShipyardQuoteLangPrefs = {
      mode: "dual",
      secondary: detected,
      active: detected,
      autoDetected: true,
    };
    saveShipyardQuoteLangPrefs(prefs);
    return prefs;
  } catch {
    window.localStorage.setItem(SHIPYARD_QUOTE_LANG_INIT_KEY, "1");
    return DEFAULT_SHIPYARD_QUOTE_LANG_PREFS;
  }
}

export function resolveActiveLocale(prefs: ShipyardQuoteLangPrefs): ShipyardQuoteLocale {
  if (prefs.mode === "en_only") return "en";
  return prefs.active === "en" ? "en" : prefs.secondary;
}
